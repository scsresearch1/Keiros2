import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { ERP_ROOT, loadEnv, log, requireEnv } from './lib/paths.mjs'

loadEnv()
requireEnv([
  'VITE_FIREBASE_API_KEY',
  'VITE_FIREBASE_AUTH_DOMAIN',
  'VITE_FIREBASE_PROJECT_ID',
  'VITE_FIREBASE_STORAGE_BUCKET',
  'VITE_FIREBASE_MESSAGING_SENDER_ID',
  'VITE_FIREBASE_APP_ID',
])

const useFirebase = process.env.VITE_USE_FIREBASE ?? 'true'
const measurement = process.env.VITE_FIREBASE_MEASUREMENT_ID
  ? `VITE_FIREBASE_MEASUREMENT_ID=${process.env.VITE_FIREBASE_MEASUREMENT_ID}\n`
  : ''

const envLocal = `# Generated by DeployCDCI — do not commit
VITE_USE_FIREBASE=${useFirebase}
VITE_FIREBASE_API_KEY=${process.env.VITE_FIREBASE_API_KEY}
VITE_FIREBASE_AUTH_DOMAIN=${process.env.VITE_FIREBASE_AUTH_DOMAIN}
VITE_FIREBASE_PROJECT_ID=${process.env.VITE_FIREBASE_PROJECT_ID}
VITE_FIREBASE_STORAGE_BUCKET=${process.env.VITE_FIREBASE_STORAGE_BUCKET}
VITE_FIREBASE_MESSAGING_SENDER_ID=${process.env.VITE_FIREBASE_MESSAGING_SENDER_ID}
VITE_FIREBASE_APP_ID=${process.env.VITE_FIREBASE_APP_ID}
${measurement}`

const envPath = path.join(ERP_ROOT, '.env.local')
fs.writeFileSync(envPath, envLocal, 'utf8')
log('wire', `Wrote ${envPath}`)

const rcPath = path.join(path.dirname(ERP_ROOT), 'DeployCDCI', '.firebaserc')
fs.writeFileSync(
  rcPath,
  JSON.stringify({ projects: { default: process.env.FIREBASE_PROJECT_ID } }, null, 2) + '\n',
  'utf8',
)
log('wire', `Updated DeployCDCI/.firebaserc → ${process.env.FIREBASE_PROJECT_ID}`)

const gitignorePath = path.join(ERP_ROOT, '.gitignore')
if (fs.existsSync(gitignorePath)) {
  let gi = fs.readFileSync(gitignorePath, 'utf8')
  const lines = ['.env', '.env.local', '.env.*.local']
  let changed = false
  for (const line of lines) {
    if (!gi.split(/\r?\n/).includes(line)) {
      gi += (gi.endsWith('\n') ? '' : '\n') + line + '\n'
      changed = true
    }
  }
  if (changed) {
    fs.writeFileSync(gitignorePath, gi, 'utf8')
    log('wire', 'Updated ERP_Full/.gitignore for env files')
  }
}

const pkg = JSON.parse(fs.readFileSync(path.join(ERP_ROOT, 'package.json'), 'utf8'))
const hasFirebase = Boolean(pkg.dependencies?.firebase)
if (!hasFirebase) {
  log('wire', 'Installing firebase in ERP_Full…')
  const r = spawnSync('npm', ['install', 'firebase@^11.6.0'], {
    cwd: ERP_ROOT,
    encoding: 'utf8',
    shell: true,
  })
  if (r.stdout) process.stdout.write(r.stdout)
  if (r.stderr) process.stderr.write(r.stderr)
  if (r.status !== 0) process.exit(r.status ?? 1)
} else {
  log('wire', 'firebase already in ERP_Full package.json')
}

log('wire', 'ERP Firebase client files should exist under ERP_Full/src/firebase/')
log('wire', 'Restart Vite after setup so .env.local is picked up.')
